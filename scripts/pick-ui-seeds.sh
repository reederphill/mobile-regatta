#!/usr/bin/env bash
# Regenerates the UI tests' seed table, RegattaUITests/SeedTable.swift (#404): each seed a UI test launches is the
# first one a headless probe finds meeting the test's condition, never a hand pick. A UI test can't sail a headless
# race at test time, so a sim or bot change that moves the outcome is one run of this script, then CI.
#
#   scripts/pick-ui-seeds.sh           probe and rewrite the table
#   scripts/pick-ui-seeds.sh --check   probe and report where the table differs, without rewriting (exit 1 if it does)
#
# The probes are `regatta-botsuite results-seed`, `rounding-seed` and `ease-seed` (Packages/RegattaCore, release build,
# through scripts/heavy.sh). Rows:
#   resultsSheet  ResultsUITests.testSheetAppearsAbout3sAfterFinishWhileSceneRenders: `-demo -laps 1 -startSeconds 10
#                 -timescale 4` (7 opponents, the launch race), your boat finishes >= 14 s of wall-clock time before the
#                 close: the sim ticks at 30 Hz and -timescale 4 runs at most 120 ticks/s, so >= 1,680 ticks (#445: at
#                 -timescale 8 the 3,360 ticks it needed were more than a one-lap fleet spreads). Her finish tick goes in
#                 the table too (`resultsSheetFinishTick`): the test watches the race clock up to it (#572). Since #583,
#                 3,600 ticks, the close's full 120 s after the first finish: she wins. The test's waits after her
#                 finish (the 3 s delay, up to 15 s for the sheet, its 20 s clock watch) outlasted the 1,899 ticks seed 8
#                 left once she finished second: CI's runner, at about 2x, reached the close under the sheet.
#   firstRounding RaceAssemblyUITests.testPracticeRaceOnTheNewCoreReachesTheGunAndAFirstRounding: `-demo -timescale 8`
#                 (the launch race, 7 opponents, 2 laps), your boat starts within 2 s of the gun and rounds the
#                 windward mark within 140 s of it with no rule call against her (#477: CI's simulator ran the race at
#                 1.25-1.4x, so the test's 180 s budget reached 157-170 s after the gun).
#   ease          EaseUITests.testEasingSlowsTheBoat: `-autostart -timescale 1` (the launch race, your boat human), clear
#                 air and a steady wind for every runner the probe models (first tap T-59 to T-40, either short ease):
#                 no other boat's ribbons or backwind on her, her wind within 5 % of the start reading's, the long
#                 ease at least 0.2 kn under the test's physics bar and under the short ease (#579: on seed 1 a fast
#                 runner read her start speed in two bots' wakes and the bar fell under the long ease).
set -euo pipefail

# The ticks from your finish to the close ResultsUITests needs: the full 120 s, she wins (#583).
results_min_gap_ticks=$((120 * 30))
# ResultsUITests' start sequence (`-startSeconds`): 10 s, not the launch race's 60, so a slow runner reaches her finish
# sooner (#572).
results_start_seconds=10
# RaceAssemblyUITests' start and first rounding, in ticks after the gun: 2 s and 140 s.
rounding_max_start_ticks=$((2 * 30))
rounding_max_rounding_ticks=$((140 * 30))

root="$(cd "$(dirname "$0")/.." && pwd)"
cd "$root"

check=false
case "${1:-}" in
    "") ;;
    --check) check=true ;;
    -h | --help) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "usage: scripts/pick-ui-seeds.sh [--check]" >&2; exit 2 ;;
esac

package=Packages/RegattaCore
scratch=.build/check/RegattaCore
probe="$scratch/release/regatta-botsuite"
build_log="$(mktemp)"
trap 'rm -f "$build_log"' EXIT
# A failed build stops here: never probe with whatever binary an earlier build left.
if ! scripts/heavy.sh swift build -c release --package-path "$package" --scratch-path "$scratch" \
    --product regatta-botsuite >"$build_log" 2>&1; then
    grep -E "error" "$build_log" >&2 || tail -20 "$build_log" >&2
    echo "pick-ui-seeds.sh: building the probe failed" >&2
    exit 1
fi
grep -E "warning: unre" "$build_log" || true
[[ -x "$probe" ]] || { echo "pick-ui-seeds.sh: no probe at $probe" >&2; exit 1; }

found="$("$probe" results-seed --from 1 --to 400 --laps 1 --opponents 7 --start-seconds "$results_start_seconds" \
    --min-gap-ticks "$results_min_gap_ticks")"
echo "resultsSheet: $found"
read -r _ seed _ finish _ close <<<"$found"
found="$("$probe" rounding-seed --from 1 --to 400 --laps 2 --opponents 7 --max-start-ticks "$rounding_max_start_ticks" \
    --max-rounding-ticks "$rounding_max_rounding_ticks")"
echo "firstRounding: $found"
read -r _ rounding_seed _ rounding_start _ rounding_tick <<<"$found"
found="$("$probe" ease-seed --from 1 --to 400)"
echo "ease: $found"
read -r _ ease_seed _ ease_margin <<<"$found"

table=RegattaUITests/SeedTable.swift
generated="$(mktemp)"
trap 'rm -f "$build_log" "$generated"' EXIT
cat >"$generated" <<SWIFT
// Generated by scripts/pick-ui-seeds.sh (#404) from a headless probe: don't edit by hand, rerun the script.

/// The seeds the UI tests launch, each the first in 1...400 meeting its test's condition.
enum SeedTable {
    /// \`ResultsUITests.testSheetAppearsAbout3sAfterFinishWhileSceneRenders\`: the \`-demo -laps 1 -startSeconds $results_start_seconds\` race
    /// on which your boat finishes at least $results_min_gap_ticks ticks before the close: she wins. Probed: she
    /// finishes at tick $finish, the race closes at $close (ticks from the gun).
    static let resultsSheet: UInt64 = $seed
    /// The tick, from the gun, your boat finishes at on \`resultsSheet\`: the test watches the race clock up to it.
    static let resultsSheetFinishTick = $finish
    /// \`RaceAssemblyUITests.testPracticeRaceOnTheNewCoreReachesTheGunAndAFirstRounding\`: the \`-demo\` launch race on which
    /// your boat starts within $rounding_max_start_ticks ticks of the gun and rounds the windward mark within $rounding_max_rounding_ticks ticks of it, with no rule
    /// call against her. Probed: she starts at tick $rounding_start and rounds at tick $rounding_tick.
    static let firstRounding: UInt64 = $rounding_seed
    /// \`EaseUITests.testEasingSlowsTheBoat\`: the \`-autostart\` launch race on which your boat sails clear air in a steady
    /// wind (no other boat's ribbons or backwind, her wind within 5 % of the start reading's) from the first tap to the
    /// long ease's release, for a first tap anywhere from T-59 to T-40, the long ease at least 0.2 kn under the test's
    /// bar. Probed: the least margin under the bar is $ease_margin kn.
    static let ease: UInt64 = $ease_seed
}
SWIFT

if cmp -s "$generated" "$table"; then
    echo "$table is up to date"
elif $check; then
    echo "pick-ui-seeds.sh: $table differs from the probe:" >&2
    diff -u "$table" "$generated" >&2 || true
    exit 1
else
    cp "$generated" "$table"
    echo "rewrote $table"
fi
